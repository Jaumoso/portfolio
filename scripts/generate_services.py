#!/usr/bin/env python3
"""Generate docs/homelab/services.md from the homelab repository.

The list of stacks comes from https://github.com/Jaumoso/homelab
(`selfhosted/` = active, `unused/` = retired). Descriptions come from
data/services.yml. Stacks without metadata are still listed as
"Uncategorised" so the page never silently drifts from reality.

Usage:
    python scripts/generate_services.py                 # read from GitHub API
    python scripts/generate_services.py --local ../homelab
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import sys
import urllib.request
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
META_FILE = ROOT / "data" / "services.yml"
OUT_FILE = ROOT / "docs" / "homelab" / "services.md"
STATS_FILE = ROOT / "docs" / "assets" / "stats.json"
DEFAULT_REPO = "Jaumoso/homelab"


def list_dirs_github(repo: str, path: str) -> list[str]:
    url = f"https://api.github.com/repos/{repo}/contents/{path}"
    req = urllib.request.Request(url, headers={"Accept": "application/vnd.github+json"})
    token = os.environ.get("GITHUB_TOKEN")
    if token:
        req.add_header("Authorization", f"Bearer {token}")
    with urllib.request.urlopen(req, timeout=30) as resp:
        items = json.load(resp)
    return sorted(i["name"] for i in items if i["type"] == "dir")


def list_dirs_local(base: Path, path: str) -> list[str]:
    d = base / path
    return sorted(p.name for p in d.iterdir() if p.is_dir() and not p.name.startswith("."))


def render(active: list[str], retired: list[str], meta: dict, repo: str) -> str:
    categories: dict = meta["categories"]
    services: dict = meta.get("services") or {}

    grouped: dict[str, list[tuple[str, dict]]] = {k: [] for k in categories}
    grouped["uncategorised"] = []
    for stack in active:
        info = services.get(stack)
        if not info or info.get("category") not in categories:
            grouped["uncategorised"].append((stack, info or {}))
        else:
            grouped[info["category"]].append((stack, info))

    own = sum(1 for s in active if services.get(s, {}).get("own"))
    on_demand = sum(1 for s in active if services.get(s, {}).get("on_demand"))
    today = dt.date.today().isoformat()

    out: list[str] = []
    out.append("# Services")
    out.append("")
    out.append("<!-- AUTO-GENERATED by scripts/generate_services.py — do not edit by hand. -->")
    out.append("")
    out.append(
        f"Everything below runs as Docker Compose stacks on the homelab. "
        f"The list is generated automatically from the [`{repo}`](https://github.com/{repo}) "
        f"repository, where the compose files live."
    )
    out.append("")
    out.append('<div class="grid cards" markdown>')
    out.append("")
    out.append(f"-   :material-docker:{{ .lg }} **{len(active)}** active stacks")
    out.append(f"-   :material-archive-outline:{{ .lg }} **{len(retired)}** tried & retired")
    out.append(f"-   :material-rocket-launch:{{ .lg }} **{own}** built by me")
    out.append(f"-   :material-power-sleep:{{ .lg }} **{on_demand}** started on demand")
    out.append("")
    out.append("</div>")
    out.append("")
    out.append(f"_Last synchronised: {today}_")
    out.append("")

    def esc(text: str) -> str:
        return (text or "").replace("|", "\\|").strip()

    order = list(categories.keys()) + ["uncategorised"]
    for key in order:
        rows = grouped.get(key) or []
        if not rows:
            continue
        if key == "uncategorised":
            title, icon = "Uncategorised", "❔"
        else:
            title, icon = categories[key]["title"], categories[key].get("icon", "")
        out.append(f"## {icon} {title}".strip())
        out.append("")
        out.append("| Service | What it is | What I use it for |")
        out.append("| ------- | ---------- | ----------------- |")
        for stack, info in sorted(rows, key=lambda r: (r[1].get("name") or r[0]).lower()):
            name = info.get("name") or stack
            if info.get("url"):
                name = f"[{name}]({info['url']})"
            name = f"**{name}**"
            tags = []
            if info.get("own"):
                tags.append(":material-star: mine")
            if info.get("on_demand"):
                tags.append(":material-power-sleep: on demand")
            if tags:
                name += "<br><small>" + " · ".join(tags) + "</small>"
            desc = esc(info.get("description") or "_Not documented yet._")
            use = esc(info.get("use") or "—")
            out.append(f"| {name} | {desc} | {use} |")
        out.append("")

    out.append("## 🗄️ Tried & retired")
    out.append("")
    out.append(
        "Stacks I have run at some point and stopped using. Their compose files are kept in "
        "`unused/` so they can be brought back in minutes."
    )
    out.append("")
    out.append(", ".join(f"`{name}`" for name in retired) if retired else "_None._")
    out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--repo", default=os.environ.get("HOMELAB_REPO", DEFAULT_REPO))
    parser.add_argument("--local", type=Path, help="Path to a local clone of the homelab repo")
    parser.add_argument("--check", action="store_true", help="Fail if services.md is out of date")
    args = parser.parse_args()

    if args.local:
        active = list_dirs_local(args.local, "selfhosted")
        retired = list_dirs_local(args.local, "unused")
    else:
        active = list_dirs_github(args.repo, "selfhosted")
        retired = list_dirs_github(args.repo, "unused")

    meta = yaml.safe_load(META_FILE.read_text(encoding="utf-8"))
    content = render(active, retired, meta, args.repo)

    undocumented = [s for s in active if s not in (meta.get("services") or {})]
    if undocumented:
        print(f"::warning::Stacks without metadata in data/services.yml: {', '.join(undocumented)}")

    stats = {
        "active": len(active),
        "retired": len(retired),
        "own": sum(1 for s in active if (meta.get("services") or {}).get(s, {}).get("own")),
    }

    def strip_date(text: str) -> str:
        return "\n".join(l for l in text.splitlines() if not l.startswith("_Last synchronised"))

    if args.check:
        current = OUT_FILE.read_text(encoding="utf-8") if OUT_FILE.exists() else ""
        if strip_date(current) != strip_date(content):
            print("services.md is out of date", file=sys.stderr)
            return 1
        return 0

    previous = OUT_FILE.read_text(encoding="utf-8") if OUT_FILE.exists() else ""
    if strip_date(previous) != strip_date(content):
        OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
        OUT_FILE.write_text(content, encoding="utf-8")
        print(f"Updated {OUT_FILE.relative_to(ROOT)}")
    else:
        print("services.md already up to date")
    STATS_FILE.parent.mkdir(parents=True, exist_ok=True)
    STATS_FILE.write_text(json.dumps(stats, indent=2) + "\n", encoding="utf-8")
    print(f"{stats['active']} active, {stats['retired']} retired, {stats['own']} own")
    return 0


if __name__ == "__main__":
    sys.exit(main())
